/**
 * SEMS Material 3 theme. Follows the system light/dark setting.
 * Dynamic color is intentionally not supported: the brand palette is always used.
 */
@Composable
fun SemsTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) SemsDarkColorScheme else SemsLightColorScheme,
        typography = SemsTypography,
        shapes = SemsShapes,
        content = content,
    )
}
