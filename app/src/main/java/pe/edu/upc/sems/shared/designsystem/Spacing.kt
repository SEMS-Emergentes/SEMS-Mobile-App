package pe.edu.upc.sems.shared.designsystem

import androidx.compose.ui.unit.dp

/** SEMS spacing: multiples of 4 dp. Cards use 16 dp padding; blocks are 24–32 dp apart. */
object SemsSpacing {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp

    val cardPadding = md
    val blockGap = lg
}
